-- CONCILIATING AMOUNT FOR EVERY COMPLETED ORDERS 
CREATE VIEW amount_conciliation AS 
(SELECT
	*,
	CASE 
		WHEN amount_paid != total_amount THEN 'Mismatched' 
		ELSE 'Matching'
	END AS amount_conciliation
FROM order_payment
WHERE status='completed');

SELECT
amount_conciliation,
COUNT(*)
FROM amount_conciliation
GROUP BY amount_conciliation;

-- CALCULATING ABSOLUTE AMOUNT OF MISMATCHED AMOUNT PAID
SELECT
(SELECT
	SUM(amount_paid) 
FROM amount_conciliation
WHERE amount_conciliation ='Mismatched') AS absolute_amount,
(SELECT
	SUM(total_amount) 
FROM amount_conciliation
WHERE amount_conciliation ='Mismatched') AS total_amount,
(SELECT
	SUM(total_amount) 
FROM amount_conciliation
WHERE amount_conciliation ='Mismatched')-
(SELECT
	SUM(amount_paid) AS amount_paid
FROM amount_conciliation
WHERE amount_conciliation ='Mismatched')AS diffrence;



-- FINDING ORDER DOESN'T HAVE PAYMENT RECORD 

SELECT
	COUNT(*)
FROM orders o
LEFT JOIN payments p
	ON o.order_id=p.order_id
WHERE p.order_id IS NULL;


-- FINDING PAYMENT DOESN'T HAVE ORDER RECORD 

SELECT
	COUNT(*)
FROM orders o
RIGHT JOIN payments p
	ON o.order_id=p.order_id
WHERE o.order_id IS NULL
;

-- COMPARING REVENUE GENERATED BY VENDORS COMLPLETED ORDER WITH VENDORS PAYOUT
DROP VIEW vendor_master;
CREATE VIEW vendor_master AS 

(
WITH vendor_rev AS 
(SELECT
	p.vendor_id,
    COALESCE(SUM(oi.quantity*oi.item_price),0) AS revenue_generated,
	CONCAT(DATE_FORMAT(MIN(o.order_date),'%b-%Y'),' - ',DATE_FORMAT(MAX(o.order_date),'%b-%Y')) AS revenue_period
FROM orders o
JOIN order_items oi
	ON o.order_id=oi.order_id
    AND o.status='Completed'
JOIN products p
	ON oi.product_id=p.product_id
GROUP BY p.vendor_id
)
,
vendor_pyt AS 
(
SELECT
	v.vendor_id,
    v.vendor_name,
    MAX(v.commission_rate) AS commission_rate,
    COALESCE(SUM(vp.payout_amount),0) AS total_payout_amount,
    CONCAT(DATE_FORMAT(MIN(vp.payout_date),'%b-%Y'),' - ',DATE_FORMAT(MAX(vp.payout_date),'%b-%Y')) AS payout_period
FROM vendors v
LEFT JOIN vendor_payouts vp
	ON v.vendor_id=vp.vendor_id
    AND v.status!='Suspended'
GROUP BY 
	v.vendor_id,
    v.vendor_name
)

SELECT 
	vp.*,
    vr.revenue_period,
    vr.revenue_generated,
    ROUND((vr.revenue_generated*(1-vp.commission_rate/100)),2) AS expected_payout,
    ROUND((vr.revenue_generated*(1-vp.commission_rate/100)),2)-total_payout_amount AS remaining 
FROM vendor_pyt vp
LEFT JOIN vendor_rev vr
	ON vp.vendor_id=vr.vendor_id
);

SELECT	
	*
FROM vendor_master
;




